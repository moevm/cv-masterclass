import os
import cv2

# Загружаем каскад Хаара -- уже обученный детектор лиц, он идёт вместе с OpenCV (код готов).
face_cascade = cv2.CascadeClassifier(cv2.data.haarcascades + "haarcascade_frontalface_default.xml")

# Путь к фотографии image.png рядом с этим файлом (менять не нужно)
FOLDER = os.path.dirname(os.path.abspath(__file__))
image_path = os.path.join(FOLDER, "image.png")


# ШАГ 1. Открываем фотографию
# TODO: замените None на команду, которая читает картинку по пути image_path.
#       Подсказка: так же, как в задании 1.
image = None

if image is None:
    print("Не получилось открыть картинку:", image_path)
    print("Проверьте ШАГ 1: дописали ли вы cv2.imread(image_path)?")
    exit()

# Детектор работает с серой картинкой, поэтому переводим её в серую (код готов)
gray_image = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)


# ШАГ 2. Ищем лица
# TODO: замените [] на команду поиска лиц.
#       Подсказка: face_cascade.detectMultiScale(gray_image, 1.1, 4)
#         1.1 -- во сколько раз уменьшать картинку на каждом шаге поиска;
#         4   -- сколько раз лицо должно «найтись», чтобы детектор ему поверил.
#               Больше -- меньше ошибок, но можно пропустить настоящее лицо.
faces = []

print("Найдено лиц:", len(faces))


# ШАГ 3. Рисуем рамки (код готов)
# Для каждого лица детектор даёт 4 числа:
#   x, y -- координаты левого верхнего угла рамки, w -- ширина, h -- высота.
for (x, y, w, h) in faces:
    cv2.rectangle(image, (x, y), (x + w, y + h), (255, 0, 0), 2)   # синяя рамка толщиной 2


# Сохраняем результат
# Файл result.jpg появится в папке 3_task, рядом с этим файлом.
output_path = os.path.join(FOLDER, "result.jpg")
if cv2.imwrite(output_path, image):
    print("Готово! Результат сохранён в файл:", output_path)
else:
    print("Не получилось сохранить файл:", output_path)


